-- 4. CHAT SESSION & FREE TIER LIMIT TABLE
-- ============================================================================

/**
 * Chat Sessions Table
 * Tracks user subscription info and conversation limits
 * One session per user, updated when plan changes
 */
CREATE TABLE IF NOT EXISTS chat_sessions (
    session_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL UNIQUE,

    -- Plan information
    plan_id SMALLINT NOT NULL DEFAULT 1,  -- FREE
    active_conversations_count INT DEFAULT 0,

    -- Limits (denormalized from plan_type table for performance)
    max_conversations_allowed INT NOT NULL DEFAULT 2,
    messages_used_this_month INT DEFAULT 0,
    max_messages_per_month INT DEFAULT 100,

    -- Timestamps
    plan_started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    plan_renews_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Constraints
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (plan_id) REFERENCES plan_type(plan_id),
    CONSTRAINT valid_conversation_count CHECK (active_conversations_count >= 0 AND active_conversations_count <= max_conversations_allowed),
    CONSTRAINT valid_message_count CHECK (messages_used_this_month >= 0 AND messages_used_this_month <= max_messages_per_month)
);

-- Index for quick lookups
CREATE INDEX IF NOT EXISTS idx_chat_sessions_user_id
    ON chat_sessions(user_id);

CREATE INDEX IF NOT EXISTS idx_chat_sessions_plan_id
    ON chat_sessions(plan_id);

-- ============================================================================
-- 5. MESSAGE CACHE TABLE (Redis substitute for non-Redis setups)
-- ============================================================================

/**
 * AI Response Cache Table
 * Stores last response for fallback when Gemini is down
 * TTL managed by application or cleanup job
 */
CREATE TABLE IF NOT EXISTS ai_response_cache (
    cache_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    conversation_id UUID NOT NULL,

    -- Cached response
    request_hash VARCHAR(64) NOT NULL,  -- Hash of question for deduplication
    response_content TEXT NOT NULL,
    response_tokens INT,

    -- Metadata
    cached_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),
    hit_count INT DEFAULT 0,  -- How many times this cache was used

    -- Constraints
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (conversation_id) REFERENCES chat_conversations(conversation_id) ON DELETE CASCADE,
    CONSTRAINT valid_hash CHECK (LENGTH(request_hash) = 64)
);

-- Indexes for cache hits
CREATE INDEX IF NOT EXISTS idx_ai_response_cache_user_request
    ON ai_response_cache(user_id, request_hash)
    WHERE expires_at > CURRENT_TIMESTAMP;

CREATE INDEX IF NOT EXISTS idx_ai_response_cache_expires
    ON ai_response_cache(expires_at);

