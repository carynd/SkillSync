-- 7. VIEWS FOR COMMON QUERIES (Performance optimization)
-- ============================================================================

/**
 * View: Active Conversations Per User
 * Used frequently, so create a view to simplify queries
 */
CREATE OR REPLACE VIEW v_active_conversations AS
SELECT
    cc.conversation_id,
    cc.user_id,
    cc.title,
    cc.message_count,
    cc.last_message_at,
    cs.status_name,
    COUNT(DISTINCT cm.message_id) AS actual_message_count
FROM chat_conversations cc
LEFT JOIN conversation_status cs ON cc.status_id = cs.status_id
LEFT JOIN chat_messages cm ON cc.conversation_id = cm.conversation_id AND cm.deleted_at IS NULL
WHERE cc.deleted_at IS NULL AND cs.status_name = 'ACTIVE'
GROUP BY cc.conversation_id, cc.user_id, cc.title, cc.message_count, cc.last_message_at, cs.status_name;

/**
 * View: User Context for AI (all info needed for Gemini)
 */
CREATE OR REPLACE VIEW v_user_ai_context AS
SELECT
    u.user_id,
    u.name,
    u.current_role,
    u.target_role,
    u.skills,
    u.experience_level,
    uap.context_level_id,
    cl.level_name AS context_level,
    uap.response_style_id,
    rs.style_name AS response_style,
    rs.max_tokens,
    uap.tone_id,
    at.tone_name AS tone,
    at.system_prompt_modifier,
    uap.include_resources,
    uap.include_examples,
    uap.include_timeline,
    uap.include_user_context
FROM users u
LEFT JOIN user_ai_preferences uap ON u.user_id = uap.user_id
LEFT JOIN context_level cl ON uap.context_level_id = cl.level_id
LEFT JOIN response_style rs ON uap.response_style_id = rs.style_id
LEFT JOIN ai_tone at ON uap.tone_id = at.tone_id;

-- ============================================================================
-- 8. FUNCTION FOR AUTO-UPDATE TIMESTAMPS
-- ============================================================================

/**
 * Function to automatically update updated_at timestamp
 * Prevents forgotten timestamp updates
 */
CREATE OR REPLACE FUNCTION update_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Triggers for timestamp updates
CREATE TRIGGER trg_chat_conversations_update
BEFORE UPDATE ON chat_conversations
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();

CREATE TRIGGER trg_user_ai_preferences_update
BEFORE UPDATE ON user_ai_preferences
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();

CREATE TRIGGER trg_user_engagement_update
BEFORE UPDATE ON user_engagement
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();

CREATE TRIGGER trg_chat_sessions_update
BEFORE UPDATE ON chat_sessions
FOR EACH ROW
EXECUTE FUNCTION update_timestamp();

-- ============================================================================
-- 9. FUNCTION TO CHECK CONVERSATION LIMIT
-- ============================================================================

/**
 * Function to check if user can create new conversation
 * Returns: true if allowed, false if limit reached
 * Called from application before creating new conversation
 */
CREATE OR REPLACE FUNCTION can_user_create_conversation(user_id_param UUID)
RETURNS BOOLEAN AS $$
DECLARE
    active_count INT;
    max_allowed INT;
BEGIN
    SELECT
        active_conversations_count,
        max_conversations_allowed
    INTO active_count, max_allowed
    FROM chat_sessions
    WHERE user_id = user_id_param;

    RETURN COALESCE(active_count, 0) < COALESCE(max_allowed, 2);
END;
$$ LANGUAGE plpgsql;

