/**
 * Conversation Status Enum
 * Allows easy querying, filtering, and future status additions
 * No need to modify table structure when adding new statuses
 */
CREATE TABLE IF NOT EXISTS conversation_status (
    status_id SMALLINT PRIMARY KEY,
    status_name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO conversation_status (status_id, status_name, description) VALUES
    (1, 'ACTIVE', 'Conversation is currently active'),
    (2, 'ARCHIVED', 'Conversation archived by user'),
    (3, 'DELETED', 'Conversation soft-deleted'),
    (4, 'PAUSED', 'Conversation paused temporarily')
ON CONFLICT DO NOTHING;

