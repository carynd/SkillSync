/**
 * Chat Conversations Table
 * Stores metadata about conversations
 * Design: Minimal data, references to other tables for details
 */
CREATE TABLE IF NOT EXISTS chat_conversations (
    conversation_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,

    -- Conversation metadata
    title VARCHAR(255),
    description TEXT,

    -- Status tracking
    status_id SMALLINT NOT NULL DEFAULT 1,

    -- Message tracking
    message_count INT DEFAULT 0,
    last_message_id UUID,
    last_message_at TIMESTAMP,

    -- Summary for AI context (refreshed periodically)
    conversation_summary TEXT,
    summary_last_updated TIMESTAMP,

    -- Audit fields
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,  -- Soft delete support

    -- Constraints
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (status_id) REFERENCES conversation_status(status_id),
    CONSTRAINT valid_summary_timestamp CHECK (summary_last_updated IS NULL OR summary_last_updated <= CURRENT_TIMESTAMP)
);

-- Indexes for optimal query performance
CREATE INDEX IF NOT EXISTS idx_chat_conversations_user_id
    ON chat_conversations(user_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_chat_conversations_user_created
    ON chat_conversations(user_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_chat_conversations_status
    ON chat_conversations(status_id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_chat_conversations_last_message
    ON chat_conversations(last_message_at DESC)
    WHERE deleted_at IS NULL;

/**
 * Chat Messages Table (Hot Data - Recent messages only)
 * Stores recent messages for quick retrieval
 * Older messages are archived to MongoDB
 *
 * Strategy: Keep only last 50 messages per conversation in PostgreSQL
 * for performance, archive rest to MongoDB
 */
CREATE TABLE IF NOT EXISTS chat_messages (
    message_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id UUID NOT NULL,
    user_id UUID NOT NULL,

    -- Message content & metadata
    role_id SMALLINT NOT NULL,
    content TEXT NOT NULL,

    -- Token count for API cost estimation
    token_count INT,

    -- Message metadata
    is_cached BOOLEAN DEFAULT false,  -- True if response came from cache
    gemini_finish_reason VARCHAR(50),  -- Why Gemini stopped (STOP, SAFETY, etc)

    -- Audit fields
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMP,  -- Soft delete support

    -- Constraints
    FOREIGN KEY (conversation_id) REFERENCES chat_conversations(conversation_id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    FOREIGN KEY (role_id) REFERENCES message_role(role_id),
    CONSTRAINT valid_token_count CHECK (token_count IS NULL OR token_count > 0),
    CONSTRAINT non_empty_content CHECK (LENGTH(TRIM(content)) > 0)
);

-- Indexes for optimal query performance
CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation_created
    ON chat_messages(conversation_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_chat_messages_user_created
    ON chat_messages(user_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_chat_messages_role
    ON chat_messages(role_id)
    WHERE deleted_at IS NULL;

-- Partial index for cached messages (quick lookup)
CREATE INDEX IF NOT EXISTS idx_chat_messages_cached
    ON chat_messages(conversation_id, is_cached)
    WHERE is_cached = true AND deleted_at IS NULL;

